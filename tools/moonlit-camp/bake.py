"""
Bake the Moonlit Camp art into the wallpaper's js/assets.js and thumb.jpg.

    python tools/moonlit-camp/bake.py [debug_dir]

source.webp is a 1672x941 pixel-art painting drawn on a 4 px grid. This script:

  1. snaps it to its real pixel grid: 418x235 cells, each cell = the median of its 4x4 block,
     which removes the soft edges of the upscaled painting and gives crisp art pixels
  2. builds a 418x235 mask (RGB):  R = open water, G = open sky, B = grass where leaves can land.
     Each mask is a hand-drawn outline (image px) narrowed by a colour test, then cleaned up
  3. writes both PNGs as data: URIs into js/assets.js. Data URIs never taint a canvas, so WebGL can
     use them even when the page runs from file:// (Lively, double-clicking index.html)
  4. writes thumb.jpg for the library

With debug_dir it also saves grid.png and masks.png (mask colours over the art) there.
"""
import base64
import io
import pathlib
import sys

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parents[1] / "src-tauri" / "wallpapers" / "moonlit-camp"
W, H, CELL = 418, 235, 4

src = Image.open(HERE / "source.webp").convert("RGB")
a = np.asarray(src).astype(float)
blocks = a[: H * CELL, : W * CELL].reshape(H, CELL, W, CELL, 3).transpose(0, 2, 1, 3, 4).reshape(H, W, CELL * CELL, 3)
grid = np.clip(np.median(blocks, axis=2) + 0.5, 0, 255).astype(np.uint8)
r, g, b = (grid[..., i].astype(int) for i in range(3))


def poly(points):
    """Filled outline, points in source-image pixels."""
    m = Image.new("L", (W, H))
    ImageDraw.Draw(m).polygon([(x / CELL, y / CELL) for x, y in points], fill=255)
    return np.asarray(m) > 0


def rect(x0, y0, x1, y1):
    return poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)])


def clean(m, min_size):
    m = ndimage.binary_closing(m, np.ones((2, 2)))
    lab, n = ndimage.label(m)
    sizes = ndimage.sum(m, lab, range(1, n + 1))
    keep = np.isin(lab, [i + 1 for i, s in enumerate(sizes) if s >= min_size])
    holes = ndimage.binary_fill_holes(keep) & ~keep
    hl, hn = ndimage.label(holes)
    hs = ndimage.sum(holes, hl, range(1, hn + 1))
    small = np.isin(hl, [i + 1 for i, s in enumerate(hs) if s <= 3])
    return keep | small


# --- water: the lake inside its shoreline, minus rocks, grass and the boy -------------------------
WATER_OUTLINE = [(0, 612), (100, 606), (300, 604), (385, 572), (400, 556), (1115, 556), (1125, 640),
                 (1095, 690), (860, 698), (745, 712), (735, 760), (870, 790), (1000, 800), (1120, 812),
                 (1250, 800), (1320, 830), (1300, 941), (230, 941), (225, 790), (150, 760), (60, 760), (0, 770)]
water_colour = ((r < 14) & (b >= g) & (b >= 10)) | ((b > 120) & (b >= r))   # deep navy, or the moon streak
fire_reflection = rect(980, 780, 1060, 912)
water = clean(poly(WATER_OUTLINE) & (water_colour | fire_reflection), 8)

# --- sky: above the pines and mountains, minus the maple canopy -------------------------------------
SKY_OUTLINE = [(0, 0), (750, 0), (790, 40), (930, 70), (945, 140), (1150, 150), (1160, 230), (1060, 250),
               (900, 280), (720, 300), (560, 300), (420, 290), (300, 270), (250, 240), (170, 190),
               (100, 140), (60, 100), (0, 120)]
red = (r > g * 1.4) & (r > 30)
sky = clean(poly(SKY_OUTLINE) & (((b >= 19) & (b > r + 10) & ~red) | (b > 200)), 6)

# --- ground: the grassy bank where falling leaves come to rest -------------------------------------
GROUND_OUTLINE = [(860, 700), (950, 690), (1100, 688), (1170, 700), (1300, 690), (1350, 665), (1600, 670),
                  (1672, 690), (1672, 790), (1500, 800), (1350, 780), (1250, 760), (1100, 735), (950, 725), (870, 722)]
ground = poly(GROUND_OUTLINE) & ~water

mask = np.zeros((H, W, 3), np.uint8)
mask[..., 0] = water * 255
mask[..., 1] = sky * 255
mask[..., 2] = ground * 255


def data_uri(arr):
    buf = io.BytesIO()
    Image.fromarray(arr).save(buf, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


js = f'''/*
 * assets.js: GENERATED by tools/moonlit-camp/bake.py. Do not edit by hand.
 *
 * SCENE_URI  the painting snapped to its real pixel grid, {W}x{H} cells
 * MASK_URI   {W}x{H} masks: R = open water, G = open sky, B = grass where leaves can land
 *
 * Defines: ART_W, ART_H, SCENE_URI, MASK_URI
 */
"use strict";
const ART_W = {W}, ART_H = {H};
const SCENE_URI = "{data_uri(grid)}";
const MASK_URI = "{data_uri(mask)}";
'''
(OUT / "js").mkdir(parents=True, exist_ok=True)
(OUT / "js" / "assets.js").write_text(js, encoding="utf-8")
src.resize((640, 360), Image.LANCZOS).save(OUT / "thumb.jpg", quality=86)
print(f"assets.js {len(js) // 1024} KB, water {water.sum()} cells, sky {sky.sum()}, ground {ground.sum()}")

if len(sys.argv) > 1:
    dbg = pathlib.Path(sys.argv[1])
    Image.fromarray(grid).resize((W * 4, H * 4), Image.NEAREST).save(dbg / "grid.png")
    over = (grid * 0.45 + mask * 0.55).astype(np.uint8)
    Image.fromarray(over).resize((W * 4, H * 4), Image.NEAREST).save(dbg / "masks.png")
